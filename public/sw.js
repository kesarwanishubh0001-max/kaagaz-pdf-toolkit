const CACHE_NAME = 'kaagaz-local-cache-v2';

const CORE_PRECACHE_URLS = [
  './',
  './index.html',
  './ocr/worker.min.js',
  './ocr/tessdata/eng.traineddata.gz',
  './ocr/tessdata/hin.traineddata.gz',
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE_NAME)
      .then((cache) =>
        Promise.allSettled(
          CORE_PRECACHE_URLS.map((url) =>
            cache.add(new Request(url, { cache: 'reload' })).catch(() => undefined)
          )
        )
      )
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))
        )
      )
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  // Never intercept SEO or site verification files
  if (
    url.pathname === '/sitemap.xml' ||
    url.pathname === '/robots.txt' ||
    /^\/google[a-z0-9]+\.html$/i.test(url.pathname)
  ) {
    return;
  }

  // Navigation requests: network first with cached index.html fallback
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response && response.ok) {
            const copy = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
          }
          return response;
        })
        .catch(() => caches.match(request).then((m) => m || caches.match('./index.html')))
    );
    return;
  }

  // Static JS, CSS, fonts, WASM, and local OCR models: cache-first with background refresh
  event.respondWith(
    caches.match(request).then((cached) => {
      if (cached) {
        return cached;
      }
      return fetch(request).then((response) => {
        if (response && response.ok) {
          const copy = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
        }
        return response;
      });
    })
  );
});
